#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const distDir = path.join(rootDir, 'dist');
const changelogPath = path.join(rootDir, 'CHANGELOG.md');
const readmePath = path.join(rootDir, 'README.md');

// Ensure dist/ directory exists for vsce output
if (!fs.existsSync(distDir)) {
    fs.mkdirSync(distDir, { recursive: true });
}

if (!fs.existsSync(changelogPath) || !fs.existsSync(readmePath)) {
    process.exit(0);
}

const rawChangelog = fs.readFileSync(changelogPath, 'utf8');
const rawReadme = fs.readFileSync(readmePath, 'utf8');

// Normalize CHANGELOG.md headings so they nest cleanly under "## Changelog" in README.md
const formattedLines = [];
for (const line of rawChangelog.split(/\r?\n/)) {
    if (/^#\s+changelog\s*$/i.test(line.trim())) {
        continue;
    }
    if (/^---\s*$/.test(line.trim())) {
        continue;
    }
    // Version headings generated by semantic-release ("# 1.1.0 ..." or "## 1.0.0 ...") -> "### ..."
    if (/^#{1,2}\s+\[?\d+\.\d+\.\d+/.test(line) || /^##\s+\[Unreleased\]/i.test(line)) {
        formattedLines.push(line.replace(/^#{1,2}\s+/, '### '));
    } else if (/^###\s+/.test(line)) {
        // Section headings ("### Features", "### Bug Fixes") -> "#### ..."
        formattedLines.push(line.replace(/^###\s+/, '#### '));
    } else {
        formattedLines.push(line);
    }
}

const syncedChangelogBody = formattedLines
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();

const changelogSectionRegex = /(## Changelog\r?\n)([\s\S]*?)(\r?\n## CLI & Development)/;
if (changelogSectionRegex.test(rawReadme)) {
    const updatedReadme = rawReadme.replace(
        changelogSectionRegex,
        `$1\n${syncedChangelogBody}\n$3`
    );
    if (updatedReadme !== rawReadme) {
        fs.writeFileSync(readmePath, updatedReadme, 'utf8');
        console.log('Synchronized ## Changelog section in README.md from CHANGELOG.md.');
    }
}
